import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

const ROOT = path.join(import.meta.dirname, '..')
const ICONS = path.join(ROOT, 'packages/vue/src/icons')
const OUT = path.join(ROOT, 'apps/web/src/lib/icons-manifest.ts')

const files = (await readdir(ICONS)).filter((f) => f.endsWith('.vue')).sort()

const entries = []
for (const f of files) {
  const src = await readFile(path.join(ICONS, f), 'utf8')
  const m = src.match(/name: '(\w+)'/)
  if (!m) continue
  entries.push({ name: f.replace('.vue', ''), component: m[1] })
}

const out = `// Generated by scripts/gen-manifest.mjs — do not edit.
import type { Component } from 'vue'
${entries.map((e) => `import ${e.component} from 'hugeicons-animated-vue/icons/${e.name}.vue'`).join('\n')}

export type IconEntry = {
  name: string
  component: Component
}

export const ICON_LIST: IconEntry[] = [
${entries.map((e) => `  { name: '${e.name}', component: ${e.component} },`).join('\n')}
]
`

await mkdir(path.dirname(OUT), { recursive: true })
await writeFile(OUT, out)
console.log(`✓ icons-manifest.ts (${entries.length} icons)`)
