import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

const ROOT = path.join(import.meta.dirname, '..')
const ICONS = path.join(ROOT, 'packages/vue/src/icons')
const OUT = path.join(ROOT, 'apps/web/src/lib/icons-manifest.ts')

const files = (await readdir(ICONS)).filter((f) => f.endsWith('.vue')).sort()
const names = []
const handcrafted = []

for (const f of files) {
  const name = f.replace('.vue', '')
  names.push(name)
  const src = await readFile(path.join(ICONS, f), 'utf8')
  if (!src.includes('generated from @hugeicons/core-free-icons')) {
    const m = src.match(/name: '(\w+)'/)
    if (m) handcrafted.push({ name, component: m[1] })
  }
}

const out = `// Generated by scripts/gen-manifest.mjs — do not edit.
import { ref, type Component } from 'vue'
${handcrafted.map((e) => `import ${e.component} from 'hugeicons-animated-vue/icons/${e.name}.vue'`).join('\n')}

export type CatalogIcon = {
  name: string
  elements: [string, Record<string, string | number>][]
  animation: {
    source: 'semantic' | 'geometry' | 'handcrafted'
    donor: string
    recipe: string
    verb: string
  }
}

export const ICON_NAMES = ${JSON.stringify(names, null, 2)} as const

export const HANDCRAFTED_ICONS: Record<string, Component> = {
${handcrafted.map((e) => `  '${e.name}': ${e.component},`).join('\n')}
}

const catalogByName = new Map<string, CatalogIcon>()
export const catalogReady = ref(false)
let catalogPromise: Promise<void> | null = null

export function loadIconCatalog() {
  if (catalogPromise) return catalogPromise
  catalogPromise = fetch('/icons-catalog.json')
    .then((res) => res.json())
    .then((items: CatalogIcon[]) => {
      for (const item of items) catalogByName.set(item.name, item)
      catalogReady.value = true
    })
  return catalogPromise
}

export function generatedIcon(name: string): CatalogIcon | undefined {
  return catalogByName.get(name)
}
`

await mkdir(path.dirname(OUT), { recursive: true })
await writeFile(OUT, out)
console.log(`✓ icons-manifest.ts (${names.length} icons, ${handcrafted.length} handcrafted)`)
